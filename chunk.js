export class Chunk {
    constructor(chunkX, chunkZ, textures, scene) {
        this.chunkX = chunkX;
        this.chunkZ = chunkZ;
        this.textures = textures;
        this.scene = scene;
        this.blocks = null; // Block data will be generated by worker
        this.mesh = null;
    }

    getBlock(x, y, z) {
        if (!this.blocks || x < 0 || x >= CHUNK_SIZE || y < 0 || y >= WORLD_HEIGHT || z < 0 || z >= CHUNK_SIZE) {
            return BlockType.AIR;
        }
        return this.blocks[x + y * CHUNK_SIZE + z * CHUNK_SIZE * WORLD_HEIGHT] & 0xFF; // Get only block type
    }

    setBlock(x, y, z, blockType, cameraDirection = null) {
        if (!this.blocks || x < 0 || x >= CHUNK_SIZE || y < 0 || y >= WORLD_HEIGHT || z < 0 || z >= CHUNK_SIZE) {
            return;
        }
        const index = x + y * CHUNK_SIZE + z * CHUNK_SIZE * WORLD_HEIGHT;

        let rotationData = 0;
        if ((blockType === BlockType.WOOD_X || blockType === BlockType.WOOD_Z) && cameraDirection) {
            // For WOOD_X (east-west log), rotation represents camera's Z direction
            // For WOOD_Z (north-south log), rotation represents camera's X direction
            if (blockType === BlockType.WOOD_X) {
                // When placing east-west log, check if camera is facing more N/S or E/W
                rotationData = Math.abs(cameraDirection.z) > Math.abs(cameraDirection.x) ? 0 : 1;
            } else {
                // When placing north-south log, check if camera is facing more N/S or E/W
                rotationData = Math.abs(cameraDirection.x) > Math.abs(cameraDirection.z) ? 1 : 0;
            }
        }

        // Store block type in the first 8 bits, rotation in the next 2 bits
        // Bit 10 is used as a 'static' flag for gravity blocks
        this.blocks[index] = blockType | (rotationData << 8);
    }

    buildMeshFromData(geometriesData) {
        if (this.mesh) {
            this.dispose();
        }

        const group = new THREE.Group();

        for (const [blockType, typeGeoms] of Object.entries(geometriesData)) {
            const blockTypeNum = parseInt(blockType);

            if (blockTypeNum === BlockType.GRASS) {
                 const grassTextures = this.textures[BlockType.GRASS];
                 for (const [faceName, geomData] of Object.entries(typeGeoms)) {
                     let texture;
                     if (faceName === 'top') texture = grassTextures.top;
                     else if (faceName === 'bottom') texture = grassTextures.bottom;
                     else texture = grassTextures.side;

                     const mesh = this.createMeshFromGeometryData(geomData, texture);
                     if (mesh) group.add(mesh);
                 }
            } else if (blockTypeNum === BlockType.WOOD || blockTypeNum === BlockType.WOOD_X || blockTypeNum === BlockType.WOOD_Z) {
                const baseTextures = this.textures[BlockType.WOOD];
                for (const [faceName, geomData] of Object.entries(typeGeoms)) {
                    // This logic now correctly maps textures based on geometry buckets
                    let texture;
                    if (faceName === 'top') { // 'top' geom bucket contains rings for all log types
                         texture = baseTextures.top;
                    } else { // 'side' geom bucket contains bark
                         texture = baseTextures.side;
                    }

                    const mesh = this.createMeshFromGeometryData(geomData, texture);
                    if (mesh) group.add(mesh);
                }
            } else if (blockTypeNum === BlockType.TNT) {
                const tntTextures = this.textures[BlockType.TNT];
                for (const [faceName, geomData] of Object.entries(typeGeoms)) {
                    let texture;
                    if (faceName === 'top' || faceName === 'bottom') texture = tntTextures.top;
                    else texture = tntTextures.side;

                    const mesh = this.createMeshFromGeometryData(geomData, texture);
                    if (mesh) group.add(mesh);
                }
            } else if (blockTypeNum === BlockType.CRAFTING_TABLE) {
                const craftingTextures = this.textures[BlockType.CRAFTING_TABLE];
                for (const [faceName, geomData] of Object.entries(typeGeoms)) {
                    let texture;
                    if (faceName === 'top') texture = craftingTextures.top;
                    else if (faceName === 'bottom') texture = craftingTextures.bottom;
                    else texture = craftingTextures.side;

                    const mesh = this.createMeshFromGeometryData(geomData, texture);
                    if (mesh) group.add(mesh);
                }
            } else if (blockTypeNum === BlockType.FURNACE || blockTypeNum === BlockType.FURNACE_LIT) {
                const furnaceTextures = this.textures[blockTypeNum];
                for (const [faceName, geomData] of Object.entries(typeGeoms)) {
                    let texture;
                    if (faceName === 'front') texture = furnaceTextures.front;
                    else if (faceName === 'top' || faceName === 'bottom') texture = furnaceTextures.top;
                    else texture = furnaceTextures.side;

                    const mesh = this.createMeshFromGeometryData(geomData, texture);
                    if (mesh) group.add(mesh);
                }
            } else if (blockTypeNum === BlockType.PLANKS) {
                const plankTextures = this.textures[BlockType.PLANKS];
                // All faces of a plank block use the same texture. The worker puts all geometry in one bucket.
                const mesh = this.createMeshFromGeometryData(typeGeoms, plankTextures.side);
                if (mesh) group.add(mesh);
            } else if (blockTypeNum === BlockType.STONE_SLAB || blockTypeNum === BlockType.STONE_SLAB_TOP) {
                const mesh = this.createMeshFromGeometryData(typeGeoms, this.textures[BlockType.COBBLESTONE]);
                if (mesh) group.add(mesh);
            } else if (blockTypeNum === BlockType.LOG_SLAB || blockTypeNum === BlockType.LOG_SLAB_TOP) {
                const mesh = this.createMeshFromGeometryData(typeGeoms, this.textures[BlockType.WOOD].side);
                if (mesh) group.add(mesh);
            } else if (blockTypeNum === BlockType.PLANK_SLAB || blockTypeNum === BlockType.PLANK_SLAB_TOP) {
                const mesh = this.createMeshFromGeometryData(typeGeoms, this.textures[BlockType.PLANKS].side);
                if (mesh) group.add(mesh);
            } else if (blockTypeNum === 14) {
                const mesh = this.createMeshFromGeometryData(typeGeoms, this.textures[14]);
                if (mesh) {
                    mesh.material.transparent = true;
                    mesh.material.opacity = 0.8;
                    mesh.material.alphaTest = 0.1;
                    mesh.material.depthWrite = false;
                    mesh.renderOrder = 1;
                    group.add(mesh);
                }
            } else if (blockTypeNum === BlockType.IRON_ORE) {
                const mesh = this.createMeshFromGeometryData(typeGeoms, this.textures[BlockType.IRON_ORE]);
                if (mesh) group.add(mesh);
            } else if (blockTypeNum === BlockType.COAL_ORE) {
                const mesh = this.createMeshFromGeometryData(typeGeoms, this.textures[BlockType.COAL_ORE]);
                if (mesh) group.add(mesh);
            } else {
                const texture = this.textures[blockType];
                if (texture) {
                    const mesh = this.createMeshFromGeometryData(typeGeoms, texture);
                    if (mesh) group.add(mesh);
                }
            }
        }

        group.position.set(this.chunkX * CHUNK_SIZE, 0, this.chunkZ * CHUNK_SIZE);
        this.mesh = group;
        this.scene.add(this.mesh);
    }

    createMeshFromGeometryData(geomData, texture) {
        if (geomData.positions.length === 0) return null;

        const geometry = new THREE.BufferGeometry();
        geometry.setAttribute('position', new THREE.Float32BufferAttribute(geomData.positions, 3));
        geometry.setAttribute('normal', new THREE.Float32BufferAttribute(geomData.normals, 3));
        geometry.setAttribute('uv', new THREE.Float32BufferAttribute(geomData.uvs, 2));
        geometry.setAttribute('ao', new THREE.Float32BufferAttribute(geomData.ao, 1));
        geometry.setIndex(new THREE.Uint32BufferAttribute(geomData.indices, 1));

        const material = new THREE.MeshLambertMaterial({
            map: texture,
            flatShading: false
        });

        this.applyAOShader(material);

        return new THREE.Mesh(geometry, material);
    }

    applyAOShader(material) {
        material.onBeforeCompile = (shader) => {
            shader.vertexShader = shader.vertexShader.replace(
                '#include <common>',
                `#include <common>
                attribute float ao;
                varying float vAo;`
            );
            shader.vertexShader = shader.vertexShader.replace(
                '#include <begin_vertex>',
                `#include <begin_vertex>
                vAo = ao;`
            );
            shader.fragmentShader = shader.fragmentShader.replace(
                '#include <common>',
                `#include <common>
                varying float vAo;`
            );
            shader.fragmentShader = shader.fragmentShader.replace(
                '#include <color_fragment>',
                `#include <color_fragment>
                float aoFactor = pow(vAo, 0.5);
                diffuseColor.rgb *= mix(0.4, 1.0, aoFactor);`
            );
        };
    }

    // This is no longer used, as mesh creation is offloaded
    createMesh() {
        // ... DELETED ...
    }

    rebuild() {
        // This is handled by world.js sending a job to the worker now
    }

    dispose() {
        if (this.mesh) {
            this.scene.remove(this.mesh);
            this.mesh.traverse((child) => {
                if (child.geometry) child.geometry.dispose();
                if (child.material) child.material.dispose();
            });
        }
    }
}